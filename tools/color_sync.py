SURFACE = "#111216"


def hex_color(channels):
    return "#" + "".join(f"{max(0, min(255, round(value))):02x}" for value in channels)


def blend(first, second, amount):
    return hex_color([a * (1 - amount) + b * amount for a, b in zip(rgb(first), rgb(second))])


def contrast(first, second):
    def luminance(color):
        values = [value / 255 for value in rgb(color)]
        values = [v / 12.92 if v <= 0.04045 else ((v + 0.055) / 1.055) ** 2.4 for v in values]
        return sum(v * w for v, w in zip(values, [0.2126, 0.7152, 0.0722]))
    light, dark = sorted([luminance(first), luminance(second)], reverse=True)
    return (light + 0.05) / (dark + 0.05)


def wallpaper_override(identifier):
    """A scene's explicit scheme color can differ from its static thumbnail."""
    if not identifier:
        return None
    database = Path.home() / ".var/app/org.waywallen.waywallen/data/waywallen/waywallen-v2.db"
    if not database.is_file():
        return None
    with closing(sqlite3.connect(database.as_uri() + "?mode=ro", uri=True)) as db:
        row = db.execute("SELECT user_property_overrides FROM item WHERE id=?", (identifier,)).fetchone()
    data = json.loads(row[0]) if row and row[0] else {}
    value = data.get("waywallen.scheme_color") or data.get("schemecolor")
    if not isinstance(value, str):
        return None
    if HEX.fullmatch(value):
        channels = [v / 255 for v in rgb(value)]
    else:
        try:
            channels = [float(v) for v in value.split()]
        except ValueError:
            return None
    if len(channels) != 3 or not all(math.isfinite(v) and 0 <= v <= 1 for v in channels):
        return None
    _, saturation, brightness = colorsys.rgb_to_hsv(*channels)
    # A black/gray scene "scheme_color" is not a useful accent override.
    return hex_color([v * 255 for v in channels]) if saturation >= 0.18 and brightness >= 0.12 else None


def image_accent(image):
    from PIL import Image, ImageOps
    with Image.open(image) as opened:
        sample = ImageOps.exif_transpose(opened).convert("RGBA")
        sample.thumbnail((160, 160))
        pixels = []
        bins = [0.0] * 48
        data = sample.tobytes()
        for offset in range(0, len(data), 4):
            red, green, blue, alpha = data[offset:offset + 4]
            hue, saturation, value = colorsys.rgb_to_hsv(red / 255, green / 255, blue / 255)
            chroma = (max(red, green, blue) - min(red, green, blue)) / 255
            if alpha < 128 or saturation < 0.18 or value < 0.12 or chroma < 0.06:
                continue
            weight = chroma ** 2.5
            # Small vivid lighting details should beat large pale skin areas.
            if 0.025 < hue < 0.13 and saturation < 0.65:
                weight *= 0.25
            bins[int(hue * 48) % 48] += weight
            pixels.append((hue, saturation, value, weight))
    if not pixels or sum(bins) < 0.5:
        return None  # Truly monochrome: no arbitrary Material-You fallback hue.
    peak = max(range(48), key=lambda i: bins[(i - 1) % 48] + 2 * bins[i] + bins[(i + 1) % 48])
    selected = [p for p in pixels if min(abs(p[0] * 48 - peak - 0.5), 48 - abs(p[0] * 48 - peak - 0.5)) < 2.0]
    weight = sum(p[3] for p in selected)
    hue = math.atan2(sum(math.sin(p[0] * math.tau) * p[3] for p in selected),
                     sum(math.cos(p[0] * math.tau) * p[3] for p in selected)) / math.tau % 1
    saturation = sum(p[1] * p[3] for p in selected) / weight
    value = sum(p[2] * p[3] for p in selected) / weight
    return hex_color([v * 255 for v in colorsys.hsv_to_rgb(hue, saturation, value)])


def palette_from_image(image, identifier=None):
    binary = shutil.which("matugen")
    if not binary:
        candidate = Path.home() / ".local/lib/waywallen-selector/matugen"
        if candidate.is_file() and os.access(candidate, os.X_OK):
            binary = str(candidate)
    if not binary:
        raise ValueError("Instala Matugen para activar los colores de las aplicaciones.")
    if not image.is_file():
        raise ValueError("El fondo no tiene una miniatura disponible para extraer sus colores.")
    source = wallpaper_override(identifier) or image_accent(image)
    # An isolated empty config and --dry-run prevent external templates, hooks,
    # caching or wallpaper setters, even if the user has configured Matugen.
    with tempfile.TemporaryDirectory(prefix="selector-palette-") as directory:
        config = Path(directory) / "config.toml"
        config.write_text("[config]\n[templates]\n")
        result = subprocess.run([
            binary, "--config", str(config), "--dry-run", "--json", "hex",
            "--mode", "dark", "--type", "scheme-content" if source else "scheme-monochrome",
            "color", "hex", source or "#808080",
        ], capture_output=True, text=True, timeout=20)
    if result.returncode:
        raise ValueError("Matugen no pudo generar la paleta de esta miniatura.")
    data = json.loads(result.stdout)
    colors = {}
    for name in ["background", "on_background", "surface_container_highest",
                 "on_surface_variant", "outline", "primary", "on_primary",
                 "secondary", "tertiary", "error"]:
        value = data["colors"][name]["dark"]["color"]
        if not isinstance(value, str) or not HEX.fullmatch(value):
            raise ValueError("Matugen devolvió una paleta no compatible.")
        colors[name] = value.lower()
    # Keep surfaces charcoal rather than washing every window in a warm neutral.
    # Hue lives in accents; it is not extracted from skin or invented for gray art.
    accent = source or "#c4c6cc"
    if source:
        hue, saturation, value = colorsys.rgb_to_hsv(*(v / 255 for v in rgb(source)))
        accent = hex_color([v * 255 for v in colorsys.hsv_to_rgb(hue, max(0.55, saturation), max(0.78, value))])
    for _ in range(30):
        if contrast(accent, SURFACE) >= 4.5:
            break
        accent = blend(accent, "#ffffff", 0.04)
    tertiary = "#b9bbc2"
    if source:
        hue, saturation, value = colorsys.rgb_to_hsv(*(v / 255 for v in rgb(accent)))
        tertiary = hex_color([v * 255 for v in colorsys.hsv_to_rgb((hue - 0.07) % 1, saturation * 0.75, value)])
    colors.update(background=SURFACE, on_background="#e5e6eb",
                  surface_container_highest=blend(SURFACE, "#ffffff", 0.12),
                  on_surface_variant="#babcc5", outline=blend(accent, SURFACE, 0.40),
                  primary=accent, on_primary=SURFACE,
                  secondary=blend(accent, "#ffffff", 0.30),
                  tertiary=tertiary)
    return colors


def rgb(color):
    return tuple(int(color[i:i + 2], 16) for i in (1, 3, 5))


def set_values(text, values, separator="=", section=None):
    """Only edit named values, preserving unrelated lines, comments and order."""
    lines = text.splitlines(keepends=True)
    current = None
    seen = set()
    end = len(lines)
    found_section = section is None
    for index, line in enumerate(lines):
        stripped = line.strip()
        if stripped.startswith("[") and stripped.endswith("]"):
            if current == section and section is not None:
                end = index
                break
            current = stripped[1:-1]
            if current == section:
                found_section = True
        if section is not None and current != section:
            continue
        for key, value in values.items():
            match = re.match(r"^(\s*" + re.escape(key) + r"\s*" +
                             (r"=\s*" if separator == "=" else r"\s+") + r")(.*?)(\r?\n)?$", line)
            if match:
                lines[index] = match[1] + value + (match[3] or "\n")
                seen.add(key)
                break
    missing = [f"{key}{separator}{value}\n" for key, value in values.items() if key not in seen]
    if not found_section:
        lines.append(f"\n[{section}]\n")
        end = len(lines)
    if missing and end > 0 and not lines[end - 1].endswith("\n"):
        lines[end - 1] += "\n"
    lines[end:end] = missing
    return "".join(lines)


def css_colors(text, colors):
    if text.count(BEGIN) != text.count(END) or text.count(BEGIN) > 1:
        raise ValueError("El bloque de colores de Vesktop está incompleto; revísalo antes de continuar.")
    text = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n?", "", text, flags=re.S)
    primary = colors["primary"]
    block = f"{BEGIN}\n:root, .theme-dark, .visual-refresh {{\n"
    for name in ["brand-500", "brand-560", "brand-600", "brand-experiment",
                 "brand-experiment-500", "text-link", "text-brand"]:
        block += f"    --{name}: {primary} !important;\n"
    for name, role in {"background-floating": "background", "text-normal": "on_background",
                       "text-muted": "on_surface_variant", "header-primary": "on_background",
                       "header-secondary": "on_surface_variant", "interactive-active": "primary"}.items():
        block += f"    --{name}: {colors[role]} !important;\n"
    block += f"    --background-modifier-selected: rgba({', '.join(map(str, rgb(primary)))}, 0.18) !important;\n"
    textarea = re.search(r"--channeltextarea-background:\s*rgba\([^)]*,\s*([0-9.]+)\s*\)", text)
    if textarea:
        block += f"    --channeltextarea-background: rgba({', '.join(map(str, rgb(colors['surface_container_highest'])))}, {textarea[1]}) !important;\n"
    block += "}\n"
    # Preserve the actual alpha, not a hardcoded replacement of transparency.
    body = re.search(r"body\s*\{[^}]*background:\s*rgba\(\s*\d+\s*,\s*\d+\s*,\s*\d+\s*,\s*([0-9.]+)\s*\)", text)
    if body:
        bg = ", ".join(map(str, rgb(colors["background"])))
        block += f"body {{ background: rgba({bg}, {body[1]}) !important; }}\n"
    block += '[role="menu"], [role="dialog"], [class^="messagesPopoutWrap_"], [class^="recentMentionsPopout_"], [class^="userPopoutOuter_"] {\n'
    for name in ["primary", "secondary", "secondary-alt", "tertiary", "base-lowest", "base-lower", "base-low",
                 "surface-high", "surface-higher", "surface-highest"]:
        block += f"    --background-{name}: {colors['background']} !important;\n"
    block += "}\n"
    block += END + "\n"
    return text.rstrip("\n") + "\n\n" + block


def restore_fields(before, last, current, keys, separator="=", section=None):
    """Restore only managed values, never unrelated edits (including old ones)."""
    def positions(text, key):
        group = None
        result = []
        for index, line in enumerate(text.splitlines(keepends=True)):
            if line.strip().startswith("[") and line.strip().endswith("]"):
                group = line.strip()[1:-1]
            if section is not None and group != section:
                continue
            match = re.match(r"^\s*" + re.escape(key) +
                             (r"\s*=\s*" if separator == "=" else r"\s+") + r"(.*?)\s*$", line)
            if match:
                result.append((index, line, match[1]))
        return result

    lines = current.splitlines(keepends=True)
    for key in keys:
        original, generated, present = (positions(text, key) for text in (before, last, current))
        if [entry[2] for entry in present] == [entry[2] for entry in original]:
            continue
        if [entry[2] for entry in original] == [entry[2] for entry in generated]:
            continue
        if [entry[2] for entry in present] != [entry[2] for entry in generated]:
            raise ValueError(f"El color {key} fue editado después; no se sobrescribirá.")
        if original and len(original) != len(present):
            raise ValueError(f"La estructura de {key} cambió; revisa el respaldo.")
        for index, entry in enumerate(present):
            lines[entry[0]] = original[index][1] if original else ""
    return "".join(lines)


def ini(text):
    result = configparser.ConfigParser(interpolation=None, strict=False)
    result.optionxform = str
    result.read_string(text or "")
    return result


def kde_groups(colors):
    value = lambda key: ",".join(map(str, rgb(colors[key])))
    groups = {}
    for role in ["Button", "Complementary", "Header", "Selection", "Tooltip", "View", "Window"]:
        selected = role == "Selection"
        groups["Colors:" + role] = {
            "BackgroundNormal": value("primary" if selected else "background"),
            "BackgroundAlternate": value("primary" if selected else "surface_container_highest"),
            "ForegroundNormal": value("on_primary" if selected else "on_background"),
            "ForegroundInactive": value("on_primary" if selected else "on_surface_variant"),
            "ForegroundActive": value("on_primary" if selected else "primary"),
            "ForegroundLink": value("on_primary" if selected else "primary"),
            "ForegroundVisited": value("on_primary" if selected else "secondary"),
            "ForegroundNegative": value("error"), "ForegroundPositive": "128,198,153",
            "ForegroundNeutral": "225,191,112", "DecorationFocus": value("primary"),
            "DecorationHover": value("secondary"),
        }
    groups["WM"] = {"activeBackground": value("background"), "activeBlend": value("background"),
                    "activeForeground": value("on_background"), "inactiveBackground": value("background"),
                    "inactiveBlend": value("background"), "inactiveForeground": value("on_surface_variant")}
    groups["General"] = {"AccentColor": value("primary"), "AccentColorFromWallpaper": "false",
                         "ColorScheme": "WaywallenSelector"}
    return groups


def set_groups(text, groups):
    for group, values in groups.items():
        text = set_values(text, values, section=group)
    return text


def restore_groups(before, last, current, groups):
    for group, keys in groups.items():
        current = restore_fields(before, last, current, keys, section=group)
        # Remove sections introduced by us, but not sections now containing user keys.
        if not ini(before).has_section(group) and not dict(ini(current)[group]):
            current = re.sub(r"\n?\[" + re.escape(group) + r"\]\n(?:[ \t]*\n)*", "\n", current)
    return before if current.rstrip("\n") == before.rstrip("\n") else current


def recolor_svg(text, colors):
    """Retint paints, not SVG geometry, IDs, alpha, blur, gradients or shadows."""
    def replace(match):
        value = match[0]
        if len(value) == 4:
            value = "#" + "".join(c * 2 for c in value[1:])
        color, alpha = value[:7], value[7:]
        red, green, blue = (v / 255 for v in rgb(color))
        hue, lightness, saturation = colorsys.rgb_to_hls(red, green, blue)
        if lightness < 0.015 or lightness > 0.98:
            return value  # Pure shadow/highlight paint: preserve it exactly.
        if lightness < 0.26:
            return blend(colors["background"], "#ffffff", max(0, (lightness - 0.065) * 0.8)) + alpha
        if saturation > 0.22 and (0.49 < hue < 0.94):
            return blend(colors["primary"], "#ffffff", max(0, (lightness - 0.55) * 0.6)) + alpha
        if saturation < 0.18:
            return blend(colors["background"], colors["on_background"], min(1, lightness * 1.15)) + alpha
        return value  # Keep semantic warning/success paint and branded logos.
    return re.sub(r"#[0-9a-fA-F]{8}\b|#[0-9a-fA-F]{6}\b|#[0-9a-fA-F]{3}\b", replace, text)


class ColorSync:
    def __init__(self, home=None, config=None, state=None):
        self.home = Path(home or Path.home()).resolve()
        self.config = Path(config or os.environ.get("XDG_CONFIG_HOME", self.home / ".config")).absolute()
        self.state = Path(state or os.environ.get("XDG_STATE_HOME", self.home / ".local/state")).absolute() / "waywallen-selector/colors"
        self.vesktop = self.home / ".var/app/dev.vencord.Vesktop/config/vesktop/settings/quickCss.css"
        self.share = Path(os.environ.get("XDG_DATA_HOME", self.home / ".local/share")).absolute() if home is None else self.home / ".local/share"
        self.generated_roots = [self.share / "plasma/desktoptheme" / f"WaywallenSelector-Plasma-{slot}" for slot in "AB"]
        self.generated_roots += [self.config / "Kvantum" / f"WaywallenSelector-Kvantum-{slot}" for slot in "AB"]
        self.allowed = {
            self.config / "kitty/kitty.conf", self.config / "btop/btop.conf",
            self.config / "btop/themes/Waywallen.theme", self.config / "kwinrc", self.vesktop,
            self.config / "kdeglobals", self.config / "plasmarc", self.config / "Kvantum/kvantum.kvconfig",
            self.share / "color-schemes/WaywallenSelector.colors",
            self.config / "cava/config",
        }
        self.observed = {}

    def safe_path(self, path):
        generated = any(path.is_relative_to(root) for root in self.generated_roots)
        if (path not in self.allowed and not generated) or path.resolve() != path.absolute():
            raise ValueError(f"Ruta no administrada o enlace simbólico: {path.name}")

    def read(self, path):
        self.safe_path(path)
        text = path.read_text() if path.is_file() else None
        self.observed.setdefault(path, (text, stat.S_IMODE(path.stat().st_mode) if path.exists() else 0o600))
        return text

    def original_theme(self, path, section, key, prefix, default):
        current = ini(self.read(path)).get(section, key, fallback=default)
        if not current.startswith(prefix):
            return current
        backup = getattr(self, "backup", None)
        if backup is None:
            manifest = self.state / "backup.json"
            backup = json.loads(manifest.read_text())["files"] if manifest.is_file() and not manifest.is_symlink() else {}
        original = backup.get(str(path), {}).get("before")
        return ini(original).get(section, key, fallback=default)

    def theme_plan(self, colors, plasma):
        config = self.config / ("plasmarc" if plasma else "Kvantum/kvantum.kvconfig")
        text = self.read(config)
        if text is None:
            return {}
        section, config_key = ("Theme", "name") if plasma else ("General", "theme")
        prefix = "WaywallenSelector-Plasma-" if plasma else "WaywallenSelector-Kvantum-"
        original = self.original_theme(config, section, config_key, prefix, "PurPurNight-Plasma" if plasma else "Sweet-Blur")
        if not re.fullmatch(r"[\w.+-]+", original):
            raise ValueError("Nombre de tema no compatible.")
        roots = [self.share / "plasma/desktoptheme", Path("/usr/share/plasma/desktoptheme")] if plasma else [self.config / "Kvantum", Path("/usr/share/Kvantum")]
        source = next((base / original for base in roots if (base / original).is_dir()), None)
        if source is None:
            return {}
        current = ini(text).get(section, config_key, fallback="")
        digest = hashlib.sha256(json.dumps({"format": THEME_FORMAT_VERSION, "colors": colors}, sort_keys=True).encode()).hexdigest()
        base = roots[0]
        current_marker = base / current / ".waywallen-selector"
        same = current.startswith(prefix) and current_marker.is_file() and f"palette={digest}\n" in current_marker.read_text()
        target_name = current if same else prefix + ("B" if current == prefix + "A" else "A")
        target = base / target_name
        marker = target / ".waywallen-selector"
        if target.exists() and (not marker.is_file() or not marker.read_text().startswith(GENERATED)):
            raise ValueError("Ya existe un tema generado ajeno al selector; no se reemplazará.")
        changes = {marker: GENERATED + f"source={original}\npalette={digest}\n"}
        if plasma:
            for path in sorted(source.rglob("*")):
                if not path.is_file():
                    continue
                if path.is_symlink():
                    raise ValueError("El tema de Plasma contiene enlaces; no se copiarán.")
                relative = path.relative_to(source)
                content = path.read_text()
                if path.suffix == ".svg" and "icons" not in relative.parts and "weather" not in relative.parts:
                    content = recolor_svg(content, colors)
                elif path.name == "colors":
                    content = set_groups(content, kde_groups(colors))
                elif path.name == "metadata.json":
                    metadata = json.loads(content)
                    metadata["KPlugin"].update(Id=target_name, Name="Waywallen · " + original)
                    content = json.dumps(metadata, indent=2) + "\n"
                changes[target / relative] = content
        else:
            svg = source / (original + ".svg")
            settings = source / (original + ".kvconfig")
            if not svg.is_file() or not settings.is_file():
                return {}
            changes[target / (target_name + ".svg")] = recolor_svg(svg.read_text(), colors)
            settings_text = settings.read_text()
            role_map = {"window.color": "background", "base.color": "background", "alt.base.color": "surface_container_highest",
                        "button.color": "surface_container_highest", "highlight.color": "primary",
                        "inactive.highlight.color": "outline", "text.color": "on_background", "window.text.color": "on_background",
                        "button.text.color": "on_background", "tooltip.text.color": "on_background",
                        "highlight.text.color": "on_primary", "link.color": "primary", "link.visited.color": "secondary",
                        "progress.indicator.text.color": "on_background"}
            original_colors = ini(settings_text)["GeneralColors"] if ini(settings_text).has_section("GeneralColors") else {}
            replacements = {}
            for key, role in role_map.items():
                old_color = original_colors.get(key, "")
                alpha = old_color[7:] if re.fullmatch(r"#[0-9a-fA-F]{8}", old_color) else ""
                replacements[key] = colors[role] + alpha
            settings_text = set_values(settings_text, replacements, section="GeneralColors")
            # Preserve all alpha suffixes and all non-color Kvantum options.
            settings_text = re.sub(r"^(text\.(?:normal|focus|press|toggle)\.color=)#[0-9a-fA-F]{6}",
                                   lambda match: match[1] + colors["on_background"], settings_text, flags=re.M)
            changes[target / (target_name + ".kvconfig")] = settings_text
        if not plasma:
            # Remove only an invalid entry produced by an earlier local build;
            # never remove unrelated Kvantum settings or user color values.
            text = re.sub(r"^progress\.indicator\.text\.color=WaywallenSelector-Kvantum-[AB]\r?\n?", "", text, flags=re.M)
        changes[config] = set_values(text, {config_key: target_name}, section=section)
        return changes

    def plan(self, colors):
        changes = {}
        kitty = self.config / "kitty/kitty.conf"
        text = self.read(kitty)
        if text is not None:
            values = {"background": colors["background"], "foreground": colors["on_background"],
                      "cursor": colors["primary"], "selection_background": colors["primary"],
                      "selection_foreground": colors["on_primary"]}
            roles = {0: "surface_container_highest", 4: "secondary", 5: "primary", 6: "tertiary",
                     7: "on_surface_variant", 8: "outline", 12: "secondary", 13: "primary",
                     14: "tertiary", 15: "on_background"}
            values.update({f"color{key}": colors[role] for key, role in roles.items()})
            changes[kitty] = set_values(text, values, " ")

        btop = self.config / "btop/btop.conf"
        text = self.read(btop)
        if text is not None:
            theme = re.search(r'^\s*color_theme\s*=\s*"([^"/]+)"', text, re.M)
            if theme:
                source = self.config / "btop/themes" / (theme[1].removesuffix(".theme") + ".theme")
                # Do not replace a builtin or unknown theme. Theme files must be
                # regular local files, never followed outside the theme folder.
                if source.is_file() and source.resolve() == source.absolute():
                    theme_text = source.read_text()
                    target = self.config / "btop/themes/Waywallen.theme"
                    existing = self.read(target)
                    if existing is not None and not existing.startswith(BTOP_MARKER):
                        raise ValueError("Ya existe un tema Waywallen ajeno al selector; no se reemplazará.")
                    theme_text = theme_text.removeprefix(BTOP_MARKER)
                    values = {"main_fg": "on_background", "title": "secondary", "hi_fg": "primary",
                              "selected_bg": "primary", "selected_fg": "on_primary",
                              "inactive_fg": "outline", "graph_text": "on_background",
                              "meter_bg": "surface_container_highest", "proc_misc": "tertiary",
                              "div_line": "outline"}
                    for name in ["cpu_box", "mem_box", "net_box", "proc_box"]:
                        values[name] = "primary"
                    for name in ["cpu", "free", "cached", "available", "used", "download", "upload", "process", "temp"]:
                        for suffix, role in [("start", "tertiary"), ("mid", "secondary"), ("end", "primary")]:
                            values[f"{name}_{suffix}"] = "error" if name == "temp" and suffix == "end" else role
                    theme_text = set_values(theme_text, {f"theme[{key}]": f'"{colors[role]}"' for key, role in values.items()})
                    changes[target] = BTOP_MARKER + theme_text
                    changes[btop] = set_values(text, {"color_theme": '"Waywallen"'})

        kwin = self.config / "kwinrc"
        text = self.read(kwin)
        if text is not None and "[Round-Corners]" in text:
            values = {"OutlineColor": ",".join(map(str, rgb(colors["primary"]))),
                      "InactiveOutlineColor": ",".join(map(str, rgb(colors["outline"])))}
            changes[kwin] = set_values(text, values, section="Round-Corners")
        text = self.read(self.vesktop)
        if text is not None:
            changes[self.vesktop] = css_colors(text, colors)
        kde = self.config / "kdeglobals"
        text = self.read(kde)
        if text is not None:
            scheme = self.share / "color-schemes/WaywallenSelector.colors"
            existing = self.read(scheme)
            if existing is not None and not existing.startswith("# " + GENERATED):
                raise ValueError("Ya existe un esquema WaywallenSelector ajeno al selector.")
            groups = kde_groups(colors)
            scheme_text = "# " + GENERATED + set_groups("", groups)
            scheme_text = set_values(scheme_text, {"Name": "Waywallen Selector"}, section="General")
            changes[scheme] = scheme_text
            groups["General"]["ColorSchemeHash"] = hashlib.sha1(scheme_text.encode()).hexdigest()
            changes[kde] = set_groups(text, groups)
            changes.update(self.theme_plan(colors, plasma=True))
            changes.update(self.theme_plan(colors, plasma=False))
        cava = self.config / "cava/config"
        text = self.read(cava)
        if text is not None:
            hues = [blend(colors["primary"], colors["tertiary"], i / 7) for i in range(8)]
            changes[cava] = set_values(text, {f"gradient_color_{i + 1}": f"'{value}'" for i, value in enumerate(hues)}, section="color")
        result = {}
        backup = getattr(self, "backup", {})
        for path, content in changes.items():
            current = self.read(path)
            if any(path.is_relative_to(root) for root in self.generated_roots):
                last = backup.get(str(path), {}).get("last")
                if last is not None and current != last:
                    raise ValueError(f"{path.name} fue editado fuera del selector; no se reemplazará.")
            if current != content:
                result[path] = content
        return result

    def restore_text(self, path, entry):
        current = self.read(path)
        before, last = entry["before"], entry["last"]
        if current is None:
            raise ValueError(f"Falta {path.name}; revisa el respaldo antes de restaurar.")
        if any(path.is_relative_to(root) for root in self.generated_roots) or path.suffix == ".colors":
            if current != last:
                raise ValueError(f"{path.name} tiene cambios posteriores; no se reemplazará.")
            return before
        if path.name == "Waywallen.theme":
            if current != last:
                raise ValueError("El tema Waywallen tiene cambios posteriores; no se reemplazará.")
            return before
        if path.name == "kitty.conf":
            keys = ["background", "foreground", "cursor", "selection_background", "selection_foreground"]
            keys += [f"color{number}" for number in [0, 4, 5, 6, 7, 8, 12, 13, 14, 15]]
            return restore_fields(before, last, current, keys, " ")
        if path.name == "btop.conf":
            return restore_fields(before, last, current, ["color_theme"])
        if path.name == "kwinrc":
            return restore_fields(before, last, current, ["OutlineColor", "InactiveOutlineColor"], section="Round-Corners")
        if path.name == "kdeglobals":
            keys = ["BackgroundNormal", "BackgroundAlternate", "ForegroundNormal", "ForegroundInactive",
                    "ForegroundActive", "ForegroundLink", "ForegroundVisited", "ForegroundNegative",
                    "ForegroundPositive", "ForegroundNeutral", "DecorationFocus", "DecorationHover"]
            groups = {"Colors:" + role: keys for role in ["Button", "Complementary", "Header", "Selection", "Tooltip", "View", "Window"]}
            groups["WM"] = ["activeBackground", "activeBlend", "activeForeground", "inactiveBackground", "inactiveBlend", "inactiveForeground"]
            groups["General"] = ["AccentColor", "AccentColorFromWallpaper", "ColorScheme", "ColorSchemeHash"]
            return restore_groups(before, last, current, groups)
        if path.name == "plasmarc":
            return restore_groups(before, last, current, {"Theme": ["name"]})
        if path.name == "kvantum.kvconfig":
            return restore_groups(before, last, current, {"General": ["theme"]})
        if path == self.config / "cava/config":
            return restore_fields(before, last, current, [f"gradient_color_{i}" for i in range(1, 9)], section="color")
        pattern = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.S)
        original_block, generated_block, present_block = (pattern.findall(text) for text in (before, last, current))
        if present_block != generated_block:
            raise ValueError("El bloque de colores de Vesktop fue editado después; no se reemplazará.")
        if original_block:
            return pattern.sub(lambda _: original_block[0], current)
        # The only change outside the block was the separating blank line.
        result = re.sub(r"\n\n" + pattern.pattern + r"\n?", "\n", current, flags=re.S)
        return before if current == last and result.rstrip("\n") == before.rstrip("\n") else result

    @staticmethod
    def atomic_write(path, text, mode=0o600):
        path.parent.mkdir(parents=True, exist_ok=True)
        handle, temporary = tempfile.mkstemp(prefix=".selector-", dir=path.parent)
        try:
            with os.fdopen(handle, "w") as output:
                os.fchmod(output.fileno(), mode)
                output.write(text)
                output.flush()
                os.fsync(output.fileno())
            os.replace(temporary, path)
        finally:
            if os.path.exists(temporary):
                os.unlink(temporary)

    def write_transaction(self, changes, originals):
        done = []
        try:
            for path, text in changes.items():
                self.safe_path(path)
                if self.read(path) != originals[path][0]:
                    raise ValueError(f"{path.name} cambió durante la operación. Vuelve a intentarlo.")
                if text is None:
                    path.unlink()
                else:
                    self.atomic_write(path, text, originals[path][1])
                done.append(path)
        except Exception:
            for path in reversed(done):
                text, mode = originals[path]
                if text is None:
                    path.unlink(missing_ok=True)
                else:
                    self.atomic_write(path, text, mode)
            self.cleanup_empty_themes()
            raise

    def cleanup_empty_themes(self):
        for root in self.generated_roots:
            if root.is_dir() and not root.is_symlink():
                for directory in sorted([p for p in root.rglob("*") if p.is_dir() and not p.is_symlink()], key=lambda p: len(p.parts), reverse=True) + [root]:
                    try:
                        directory.rmdir()  # Only empty directories created for our themes.
                    except OSError:
                        pass

    def apply(self, colors=None, restore=False):
        self.state.mkdir(parents=True, exist_ok=True, mode=0o700)
        if self.state.resolve() != self.state:
            raise ValueError("El directorio de respaldo no puede ser un enlace simbólico.")
        with (self.state / "lock").open("a") as lock:
            fcntl.flock(lock, fcntl.LOCK_EX)
            manifest = self.state / "backup.json"
            if manifest.is_symlink():
                raise ValueError("El respaldo no puede ser un enlace simbólico.")
            previous = manifest.read_text() if manifest.exists() else None
            data = json.loads(previous) if previous else {"version": 1, "files": {}}
            self.backup = data["files"]
            self.observed = {}
            changes = self.plan(colors) if not restore else {}
            if restore:
                for name, entry in data["files"].items():
                    path = Path(name)
                    changes[path] = self.restore_text(path, entry)
            originals = {path: self.observed[path] for path in changes}
            for path, text in changes.items():
                entry = data["files"].setdefault(str(path), {"before": originals[path][0]})
                entry["last"] = text
            if not restore:
                # Persist the originals BEFORE changing any application files.
                self.atomic_write(manifest, json.dumps(data, indent=2) + "\n")
            try:
                self.write_transaction(changes, originals)
            except Exception:
                if previous is None:
                    manifest.unlink(missing_ok=True)
                else:
                    self.atomic_write(manifest, previous)
                raise
            if restore:
                self.atomic_write(manifest, json.dumps({"version": 1, "files": {}}) + "\n")
                self.cleanup_empty_themes()
            return changes


def reload_apps(changes):
    # Only signal processes owned by this user that actually catch this signal.
    # No remote-control socket, application restart, or KWin script reload.
    names = set()
    if any(path.name == "kitty.conf" for path in changes):
        names.add("kitty")
    if any(path.name in {"btop.conf", "Waywallen.theme"} for path in changes):
        names.add("btop")
    if any(path.parts[-2:] == ("cava", "config") for path in changes):
        names.add("cava")
    for process in Path("/proc").iterdir():
        if not process.name.isdecimal():
            continue
        try:
            if process.stat().st_uid != os.getuid():
                continue
            name = (process / "comm").read_text().strip()
            if name not in names:
                continue
            sig = signal.SIGUSR1 if name == "kitty" else signal.SIGUSR2
            caught = re.search(r"^SigCgt:\s*([0-9a-fA-F]+)", (process / "status").read_text(), re.M)
            if caught and int(caught[1], 16) & (1 << (sig - 1)):
                os.kill(int(process.name), sig)
        except (OSError, ProcessLookupError):
            pass
    parts = []
    for name, part in [("kdeglobals", "palette"), ("plasmarc", "plasma"),
                       ("kvantum.kvconfig", "kvantum"), ("kwinrc", "borders")]:
        if any(path.name == name for path in changes):
            parts.append(part)
    if "kvantum" not in parts and any(any(part.startswith("WaywallenSelector-Kvantum-") for part in path.parts) for path in changes):
        parts.append("kvantum")
    if "plasma" not in parts and any(any(part.startswith("WaywallenSelector-Plasma-") for part in path.parts) for path in changes):
        parts.append("plasma")
    if parts:
        binary = os.environ.get("WAYWALLEN_SELECTOR_BINARY") or shutil.which("waywallen-selector")
        if not binary:
            candidate = Path.home() / ".local/bin/waywallen-selector"
            binary = str(candidate) if candidate.is_file() else None
        if not binary:
            raise ValueError("Los colores se guardaron, pero falta el selector instalado para recargarlos en KDE.")
        result = subprocess.run([binary, "--reload-appearance", ",".join(parts)], capture_output=True, text=True, timeout=25)
        if result.returncode:
            raise ValueError("Los colores se guardaron, pero la recarga en vivo falló: " + result.stderr.strip()[:500])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--image", type=Path)
    group.add_argument("--restore", action="store_true")
    parser.add_argument("--dry-run", action="store_true")
    parser.add_argument("--no-reload", action="store_true")
    parser.add_argument("--wallpaper-id", help="Read the selected scene's color override (read-only).")
    args = parser.parse_args()
    if args.restore and args.dry_run:
        parser.error("--dry-run requiere --image")
    sync = ColorSync()
    colors = palette_from_image(args.image, args.wallpaper_id) if args.image else None
    if args.dry_run:
        changes = sync.plan(colors)
    else:
        changes = sync.apply(colors, args.restore)
        if not args.no_reload:
            # Retrying the same wallpaper must retry its live notifications too.
            reload_paths = changes or ({} if args.restore else {path: None for path in sync.allowed if path.is_file()})
            reload_apps(reload_paths)
    print(json.dumps({"files": [str(path) for path in changes], "colors": colors,
                      "dry_run": args.dry_run}, ensure_ascii=False))


if __name__ == "__main__":
    try:
        main()
    except (OSError, ValueError, KeyError, subprocess.SubprocessError) as error:
        print(str(error), file=sys.stderr)
        sys.exit(1)
